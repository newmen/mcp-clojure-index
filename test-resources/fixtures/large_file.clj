;; Section 5 collection helpers
(defn group-by-count
  "Like group-by but returns counts instead of groups."
  [f coll]
  (->> (group-by f coll)
       (reduce-kv (fn [acc k v] (assoc acc k (count v))) {})))

(defn frequencies-by
  "Compute frequencies of a key function applied to each element."
  [f coll]
  (->> (map f coll)
       (reduce (fn [acc x] (update acc x (fnil inc 0))) {})))

(defn partition-when
  "Partition collection when predicate is true."
  [pred coll]
  (lazy-seq
    (when-let [s (seq coll)]
      (let [[before after] (split-with (complement pred) s)
            [pivot rest] (if (seq after)
                           [(list (first after)) (rest after)]
                           [nil nil])]
        (cons (concat before pivot)
              (partition-when pred rest))))))

;; Section 6 math utilities
(defn factorial
  [n]
  (reduce * 1N (range 1 (inc n))))

(defn fibonacci
  [n]
  (->> (iterate (fn [[a b]] [b (+ a b)]) [0N 1N])
       (map first)
       (take (inc n))
       last))

(defn prime?
  [n]
  (when (>= n 2)
    (not-any? #(zero? (mod n %)) (range 2 (inc (int (Math/sqrt n)))))))

(defn gcd
  [a b]
  (if (zero? b) a (recur b (mod a b))))

(defn lcm
  [a b]
  (/ (* a b) (gcd a b)))

;; Section 7 sequence operations
(defn intersperse
  "Place separator between elements of a sequence."
  [sep coll]
  (drop 1 (interleave (repeat sep) coll)))

(defn separate
  "Split collection into [passing failing] based on predicate."
  [pred coll]
  [(filterv pred coll) (filterv (complement pred) coll)])

(defn take-until
  "Take elements until predicate is true (inclusive)."
  [pred coll]
  (let [[before after] (split-with (complement pred) coll)]
    (concat before (take 1 after))))

(defn drop-until
  "Drop elements until predicate is true, then return rest."
  [pred coll]
  (second (split-with (complement pred) coll)))

(defn shuffle
  "Fisher-Yates shuffle."
  [coll]
  (let [arr (into-array coll)
        n (alength arr)]
    (doseq [i (range n)]
      (let [j (+ i (rand-int (- n i)))
            tmp (aget arr i)]
        (aset arr i (aget arr j))
        (aset arr j tmp)))
    (vec arr)))

