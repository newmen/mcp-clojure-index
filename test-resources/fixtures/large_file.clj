;; Section 2 data processing
(defn aggregate
  "Aggregate a collection of values into a summary map."
  [values]
  (reduce (fn [acc v]
            (-> acc
                (update :sum + v)
                (update :count inc)
                (update :max #(max % v))
                (update :min #(min % v))))
          {:sum 0 :count 0 :max 0 :min ##Inf}
          values))

(defn normalize
  "Normalize values to 0-1 range."
  [values]
  (let [mx (apply max values)
        mn (apply min values)
        diff (- mx mn)]
    (if (zero? diff)
      (repeat (count values) 0.5)
      (mapv #(/ (- % mn) diff) values))))

(defn filter-outliers
  "Remove values outside 2 standard deviations from mean."
  [values]
  (let [n (count values)
        mean (/ (reduce + values) n)
        variance (/ (reduce + (map #(* (- % mean) (- % mean)) values)) n)
        stddev (Math/sqrt variance)
        lower (- mean (* 2 stddev))
        upper (+ mean (* 2 stddev))]
    (filterv #(and (>= % lower) (<= % upper)) values)))

(defn moving-average
  "Compute moving average with given window size."
  [values window]
  (let [n (count values)]
    (mapv (fn [i]
            (let [start (max 0 (- i window -1))
                  end (inc i)
                  slice (subvec (vec values) start end)]
              (/ (reduce + slice) (count slice))))
          (range n))))

;; Section 3 string utilities
(defn camel->snake
  "Convert CamelCase to snake_case."
  [s]
  (-> s
      (str/replace #"([A-Z]+)([A-Z][a-z])" "$1_$2")
      (str/replace #"([a-z0-9])([A-Z])" "$1_$2")
      (s/lower-case)))

(defn snake->camel
  "Convert snake_case to CamelCase."
  [s]
  (->> (str/split s #"_")
       (mapv str/capitalize)
       (str/join "")))

(defn truncate
  "Truncate string to max-length with ellipsis."
  [s max-len]
  (if (<= (count s) max-len)
    s
    (str (subs s 0 max-len) "...")))

