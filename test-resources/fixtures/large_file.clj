(defn retry
  "Retry an operation up to n times with exponential backoff."
  [n f]
  (loop [attempt 1]
    (let [result (try
                   {:ok (f)}
                   (catch Exception e
                     {:error e}))]
      (if (:ok result)
        (:ok result)
        (if (< attempt n)
          (do (Thread/sleep (* 100 (long (Math/pow 2 attempt))))
              (recur (inc attempt)))
          (throw (:error result)))))))

