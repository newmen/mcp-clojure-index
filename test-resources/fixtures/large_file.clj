;; Section 22 rate limiting
(defonce rate-limiter (atom {}))

(defn rate-limit
  "Ensure at most n calls per window-ms."
  [key n window-ms f]
  (let [now (System/currentTimeMillis)
        state (get @rate-limiter key [])
        window-start (- now window-ms)
        recent (filterv #(> % window-start) state)]
    (if (< (count recent) n)
      (do (swap! rate-limiter update key (fn [v] (conj (vec (take-last n (or v []))) now)))
          (f))
      (throw (ex-info "Rate limit exceeded" {:key key :limit n})))))

;; Section 23 circuit breaker
(defonce circuit-breaker (atom {}))

(defn call-with-circuit-breaker
  "Circuit breaker pattern: fail-fast when failure threshold is reached."
  [key threshold reset-ms f]
  (let [state (get @circuit-breaker key {:failures 0 :last-failure 0 :open false})
        now (System/currentTimeMillis)]
    (if (and (:open state) (< (- now (:last-failure state)) reset-ms))
      (throw (ex-info "Circuit breaker open" {:key key}))
      (try
        (let [result (f)]
          (when (:open state)
            (swap! circuit-breaker assoc key {:failures 0 :open false}))
          result)
        (catch Exception e
          (let [new-state (update state :failures (fnil inc 0))]
            (swap! circuit-breaker assoc key (assoc new-state
                                              :last-failure now
                                              :open (>= (:failures new-state) threshold)))
            (throw e)))))))

;; Section 24 caching
(defn ttl-cache
  "Create a time-to-live cache atom."
  [ttl-ms]
  (atom {:data {} :ttl ttl-ms}))

(defn cache-get
  [cache key]
  (let [state @cache
        entry (get (:data state) key)]
    (when entry
      (if (< (- (System/currentTimeMillis) (:time entry)) (:ttl state))
        (:value entry)
        (do (swap! cache update :data dissoc key) nil)))))

(defn cache-put
  [cache key value]
  (swap! cache assoc-in [:data key] {:value value :time (System/currentTimeMillis)}))

