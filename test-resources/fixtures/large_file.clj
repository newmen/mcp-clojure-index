;; Section 26 data transformation
(defn pivot
  "Simple pivot: given a coll of maps, group by key1 and key2."
  [coll key1 key2 val-fn]
  (reduce (fn [acc m]
            (let [k1 (get m key1)
                  k2 (get m key2)
                  v (val-fn m)]
              (update-in acc [k1 k2] (fnil + 0) v)))
          {} coll))

(defn fill-gaps
  "Fill nil values with the preceding non-nil value."
  [coll]
  (reductions (fn [prev v] (if (nil? v) prev v)) coll))

