;; Section 13 comparators
(defn by-key
  [k]
  (fn [a b] (compare (get a k) (get b k))))

(defn descending
  [f]
  (fn [a b] (compare (f b) (f a))))

(defn then-by
  [& fns]
  (fn [a b]
    (loop [[f & rest] fns]
      (let [c (compare (f a) (f b))]
        (if (and (zero? c) (seq rest))
          (recur rest)
          c)))))

;; Section 14 memoization
(defonce memo-cache (atom {}))

(defn memo
  [f]
  (fn [& args]
    (let [key args]
      (if-let [cached (get @memo-cache key)]
        cached
        (let [result (apply f args)]
          (swap! memo-cache assoc key result)
          result)))))

;; Section 15 protocols and records
(defprotocol Serializer
  (serialize [this])
  (deserialize [this data]))

(defrecord UserRecord [id name email]
  Serializer
  (serialize [this]
    (str (:id this) "," (:name this) "," (:email this)))
  (deserialize [this data]
    (let [[id name email] (str/split data #",")]
      (UserRecord. id name email))))

(defrecord ConfigRecord [host port timeout]
  Serializer
  (serialize [this]
    (str (:host this) ":" (:port this)))
  (deserialize [this data]
    (let [[host port] (str/split data #":")]
      (ConfigRecord. host (Integer/parseInt port) nil))))

